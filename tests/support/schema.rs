const COLUMNS: &str =
    "SELECT table_name::text, column_name::text, data_type::text, is_nullable::text,
       column_default::text, is_identity::text, identity_generation::text
FROM information_schema.columns
WHERE table_schema = current_schema() AND NOT table_name::text = ANY($1)";

const CONSTRAINTS: &str =
    "SELECT conrelid::regclass::text, conname::text, pg_get_constraintdef(oid)
FROM pg_constraint
WHERE connamespace = (SELECT oid FROM pg_namespace WHERE nspname = current_schema())
  AND NOT conrelid::regclass::text = ANY($1)";

const INDEXES: &str = "SELECT indexdef FROM pg_indexes
WHERE schemaname = current_schema() AND NOT tablename::text = ANY($1)";

const SEQUENCES: &str =
    "SELECT s.sequencename::text, s.data_type::text, s.start_value, s.increment_by
FROM pg_sequences s
WHERE s.schemaname = current_schema() AND NOT EXISTS (
    SELECT 1 FROM pg_depend d JOIN pg_class t ON t.oid = d.refobjid
    WHERE d.classid = 'pg_class'::regclass AND d.refclassid = 'pg_class'::regclass
      AND d.objid = format('%I.%I', s.schemaname, s.sequencename)::regclass
      AND t.relname::text = ANY($1))";

pub async fn schema_snapshot(client: &Client, leave_out: &[&str]) -> Vec<String> {
    let leave_out: Vec<String> = leave_out.iter().map(|&table| table.to_owned()).collect();
    let parameters: [&(dyn ToSql + Sync); 1] = [&leave_out];
    let (columns, constraints, indexes, sequences) = tokio::try_join!(
        client.query(COLUMNS, &parameters),
        client.query(CONSTRAINTS, &parameters),
        client.query(INDEXES, &parameters),
        client.query(SEQUENCES, &parameters),
    )
    .expect("read the catalog");
    let mut lines: Vec<String> = columns
        .iter()
        .map(|row| {
            let default: Option<String> = row.get(4);
            let generation: Option<String> = row.get(6);
            format!(
                "column {}.{} {} nullable={} default={default:?} identity={} {generation:?}",
                row.get::<_, String>(0),
                row.get::<_, String>(1),
                row.get::<_, String>(2),
                row.get::<_, String>(3),
                row.get::<_, String>(5),
            )
        })
        .chain(constraints.iter().map(|row| {
            format!(
                "constraint {} {} {}",
                row.get::<_, String>(0),
                row.get::<_, String>(1),
                row.get::<_, String>(2),
            )
        }))
        .chain(
            indexes
                .iter()
                .map(|row| format!("index {}", row.get::<_, String>(0))),
        )
        .chain(sequences.iter().map(|row| {
            format!(
                "sequence {} {} start={} increment={}",
                row.get::<_, String>(0),
                row.get::<_, String>(1),
                row.get::<_, i64>(2),
                row.get::<_, i64>(3),
            )
        }))
        .collect();
    lines.sort();
    lines
}

pub async fn up_sections(client: &Client, versions: &[i64]) {
    for version in versions {
        let (_, file) = GOOSE_FILES
            .iter()
            .find(|(known, _)| known == version)
            .unwrap_or_else(|| panic!("no goose file for version {version}"));
        let (up, _) = file.split_once("-- +goose Down").expect("a down section");
        client
            .batch_execute(up)
            .await
            .unwrap_or_else(|error| panic!("apply goose version {version}: {error:?}"));
    }
}

pub async fn goose_era_database(client: &Client, applied: &[i64], recorded: &[i64]) {
    client
        .batch_execute(
            "CREATE TABLE goose_db_version (
                id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                version_id bigint NOT NULL,
                is_applied boolean NOT NULL,
                tstamp timestamp NOT NULL DEFAULT now()
            );
            INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)",
        )
        .await
        .expect("create goose_db_version");
    up_sections(client, applied).await;
    for version in recorded {
        client
            .execute(
                "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)",
                &[version],
            )
            .await
            .expect("record a goose version");
    }
}

