pub async fn table_names(client: &Client) -> Vec<String> {
    let mut names: Vec<String> = client
        .query(
            "SELECT tablename::text FROM pg_tables WHERE schemaname = current_schema()",
            &[],
        )
        .await
        .expect("list the tables")
        .iter()
        .map(|row| row.get(0))
        .collect();
    names.sort();
    names
}

pub async fn rows(client: &Client, table: &str) -> Vec<String> {
    client
        .query(
            &format!("SELECT row_to_json(t)::text FROM {table} t ORDER BY 1"),
            &[],
        )
        .await
        .unwrap_or_else(|error| panic!("read {table}: {error:?}"))
        .iter()
        .map(|row| row.get(0))
        .collect()
}
